#!/usr/bin/env bash
# Copy production's public news content into supabase/seed/content.sql, which
# `supabase db reset` loads into the LOCAL database after the migrations.
#
# Read-only against production: `db dump` runs pg_dump and writes nothing there.
# Only public content is copied. Every table that holds people (readers,
# subscribers, contact messages, push tokens, staff) is excluded, and the two
# person fields inside content tables are blanked on load:
#   authors.email        journalists' addresses
#   articles.created_by  staff accounts in auth.users, which are not copied
#
# The output is gitignored: regenerate it whenever you want fresher stories.
# Run from the repo root:  bash supabase/scripts/dump-content.sh
set -euo pipefail

cd "$(dirname "$0")/../.."
out=supabase/seed/content.sql
raw=$(mktemp)
trap 'rm -f "$raw"' EXIT

keep="articles article_tags authors categories tags forex_rates live_updates"

# db dump has no "only these tables" flag for data, so exclude everything else.
exclude=$(
  grep -oE '^CREATE TABLE IF NOT EXISTS "public"\."[a-z_]+"' supabase/migrations/*_baseline.sql \
    | sed -E 's/.*"public"\."([a-z_]+)"/\1/' \
    | grep -vxF -f <(tr ' ' '\n' <<<"$keep") \
    | sed 's/^/public./' | paste -sd, -
)

supabase db dump --remote --data-only --schema public --exclude "$exclude" -f "$raw"

mkdir -p supabase/seed
{
  echo "-- Generated by supabase/scripts/dump-content.sh. Do not commit."
  # Replica mode skips triggers and foreign-key checks while loading: the
  # breaking-news webhook must not fire for hundreds of old stories, and
  # articles.created_by points at staff users that don't exist locally.
  echo "set session_replication_role = replica;"
  cat "$raw"
  echo "set session_replication_role = origin;"
  echo "update public.authors set email = null;"
  echo "update public.articles set created_by = null;"
  # As in production: every breaking story already published counts as pushed,
  # so editing one locally doesn't send a push for old news.
  echo "insert into public.mobile_push_log (article_id)"
  echo "  select id from public.articles where status = 'published' and is_breaking"
  echo "  on conflict do nothing;"
} >"$out"

echo "Wrote $out ($(wc -c <"$out") bytes). Now run: supabase db reset"
